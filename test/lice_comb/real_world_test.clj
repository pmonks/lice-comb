(defn public-domain-only?
  "Does the given set of ids contain only a single public domain LicenseRef?"
  [ids]
  (and (= 1 (count ids))
       (public-domain? (first ids))))

(defn unidentified-only?
  "Does the given set of ids contain only a single unidentified LicenseRef?"
  [ids]
  (and (= 1 (count ids))
       (unidentified? (first ids))))

(defn proprietary-only?
  "Does the given set of ids contain only a single proptietary/commercial LicenseRef?"
  [ids]
  (and (= 1 (count ids))
       (proprietary-commercial? (first ids))))

